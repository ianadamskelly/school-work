import assert from 'node:assert/strict';
import {weekStart,addDays,focusProgress,objectiveProgress,weeklyText} from '../lib/journal.ts';
const entry=(id,kind,data)=>({id,kind,data,revision:'test'});
const o=entry('o','objective',{title:'Test objective',month:'2026-11'});
const f=entry('f','focus',{objectiveId:'o',title:'Checks',target:10,weight:3,unit:'accounts'});
const g=entry('g','focus',{objectiveId:'o',title:'Milestone',target:1,weight:1,unit:'milestone'});
const a=entry('a','activity',{title:'Four checks',date:'2026-11-15',type:'planned',status:'done',focusId:'f',contribution:4,outcome:'Four confirmed',minutes:30});
let es=[o,f,g,a];
assert.equal(focusProgress(f,es).percent,40);
assert.equal(objectiveProgress(o,es),30);
const routine=entry('r','activity',{...a.data,type:'recurring',focusId:'',contribution:0,title:'Routine support'});
assert.equal(objectiveProgress(o,[...es,routine]),30);
assert.equal(focusProgress(f,[o,f,{...a,data:{...a.data,status:'planned'}}]).percent,0);
assert.equal(focusProgress(f,[o,f,{...a,data:{...a.data,status:'blocked'}}]).percent,0);
assert.equal(focusProgress(f,[o,f,{...a,data:{...a.data,contribution:12}}]).percent,100);
assert.equal(objectiveProgress(o,[o,f,g]),0);
assert.equal(weekStart('2026-11-14'),'2026-11-14');
assert.equal(weekStart('2026-11-20'),'2026-11-14');
assert.equal(weekStart('2026-11-21'),'2026-11-21');
assert.equal(weekStart('2027-01-01'),'2026-12-26');
assert.equal(addDays('2026-12-31',1),'2027-01-01');
const blocked=entry('b','activity',{...a.data,title:'Blocked checks',status:'blocked',challenge:'Access unavailable',solution:'Request access',contribution:0});
const next=entry('n','activity',{...a.data,title:'Follow up next week',date:'2026-11-21',status:'planned',contribution:0});
const t=weeklyText([...es,blocked,next], '2026-11-14',{reportedBy:'Ian',updates:'Additional context'});
for(const v of ['A. Updates','B. Challenges','C. Recommended solutions','D. Plan for next week','Four confirmed','Access unavailable','Request access','Follow up next week','Additional context'])assert.ok(t.includes(v),v);
assert.ok(!t.split('B. Challenges')[0].includes('Blocked checks'));
console.log('Passed: weighted progress, zero routine credit, status rules, cap, deletion recalculation, week/year boundaries, structured report and next-week plan.');
const {canWork,canEditPlan,unitSuggestions}=await import('../lib/workflow.ts');
assert.equal(canWork(o),true); // Older objectives without workflow metadata retain history.
assert.equal(canWork({...o,data:{...o.data,approvalStatus:'draft'}}),false);
assert.equal(canWork({...o,data:{...o.data,approvalStatus:'submitted'}}),false);
assert.equal(canWork({...o,data:{...o.data,approvalStatus:'approved'}}),true);
assert.equal(canEditPlan({...o,data:{...o.data,approvalStatus:'changes-requested'}}),true);
assert.ok(unitSuggestions.includes('student submissions'));
console.log('Passed: legacy compatibility, approval status gates and unit suggestions.');
